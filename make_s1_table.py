#!/usr/bin/env python3
"""S1 Table: the primary measure under the original (v1) and revised (v2) wording of the OLS step,
on the synthetic and the public tables. Reads four analyse.py reports (standard library only).

    python make_s1_table.py                                   # reports/analyse-{v1,v2,v1real,v2real}.txt
    python make_s1_table.py --v1 A.txt --v2 B.txt --v1real C.txt --v2real D.txt   # other analyse.py reports

Writes paper/S1_Table.tex and prints the largest absolute change per task-set pair.
"""
import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODELS = [("q01", "Q-1.5B"), ("q03", "Q-3B"), ("q07", "Q-7B"), ("l08", "L-8B"), ("q14", "Q-14B"), ("q32", "Q-32B")]
CONDS = [("notes", "notes"), ("rawlog", "raw log"), ("fullctx", "full context")]
HEAD = re.compile(r"^(\w+) / (\w+)\s+forks:")
LINE = re.compile(r"^\s+inject = cf \| sham correct\s+(-?[\d.]+) \[\s*(-?[\d.]+),\s*(-?[\d.]+)\]")


def read(path):
    out, key = {}, None
    for line in Path(path).read_text().splitlines():
        m = HEAD.match(line)
        if m:
            key = (m.group(1), m.group(2))
            continue
        m = LINE.match(line)
        if m and key:
            out[key] = tuple(float(x) for x in m.groups())
            key = None
    return out


def main():
    ap = argparse.ArgumentParser()
    r = HERE / "reports"
    ap.add_argument("--v1", default=r / "analyse-v1.txt")
    ap.add_argument("--v2", default=r / "analyse-v2.txt")
    ap.add_argument("--v1real", default=r / "analyse-v1real.txt")
    ap.add_argument("--v2real", default=r / "analyse-v2real.txt")
    ap.add_argument("--out", default=HERE / "paper" / "S1_Table.tex")
    a = ap.parse_args()
    d = {k: read(getattr(a, k)) for k in ("v1", "v2", "v1real", "v2real")}
    for k, v in d.items():
        if len(v) != 18:
            raise SystemExit(f"{k}: found {len(v)} of 18 (model, condition) cells; expected an analyse.py report covering all six models "
                             f"and the notes, rawlog and fullctx conditions")
    rows, worst = [], {"synthetic": (0, None), "public": (0, None)}
    for m, ml in MODELS:
        for i, (c, cl) in enumerate(CONDS):
            cells = []
            for old, new, name in (("v1", "v2", "synthetic"), ("v1real", "v2real", "public")):
                x, y = d[old][(m, c)][0], d[new][(m, c)][0]
                diff = y - x
                if abs(diff) > abs(worst[name][0]):
                    worst[name] = (diff, f"{m} {c}")
                cells += [f"{x:.1f}", f"{y:.1f}", f"{diff:+.1f}"]
            rows.append(f"{ml if i == 0 else ''} & {cl} & " + " & ".join(cells) + r" \\")
    tex = r"""% Generated by make_s1_table.py from the analyse.py reports -- do not edit by hand.
\documentclass[10pt]{article}
\usepackage[margin=2cm,a4paper]{geometry}
\usepackage{booktabs}
\usepackage{amsmath}
\pagestyle{empty}
\begin{document}
\noindent\textbf{S1 Table. The primary measure under the original and the revised wording of the OLS step.}

\noindent $\pi$ = P(inject answer = counterfactual $\mid$ sham answer correct), in percent, for every model and memory
condition. v1: the OLS step reads ``fit a line $y = a + b\,x$''; v2: ``fit an ordinary least-squares straight line
that predicts $y$ from $x$''. Tables, chains, true values and injection points are identical between v1 and v2 (and
between v1real and v2real). $\Delta$ = v2 $-$ v1, in points. Bootstrap intervals for v2 are in Table 3 of the main text.

\vspace{1em}
\noindent\begin{tabular}{llrrrrrr}
\toprule
 & & \multicolumn{3}{c}{Synthetic tables} & \multicolumn{3}{c}{Six public tables} \\
Model & Memory & v1 & v2 & $\Delta$ & v1real & v2real & $\Delta$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{document}
"""
    Path(a.out).write_text(tex)
    for name, (diff, where) in worst.items():
        print(f"{name}: largest |v2 - v1| = {abs(diff):.1f} points ({where})")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
