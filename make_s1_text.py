#!/usr/bin/env python3
"""S1 Text: the prompts, rendered by the agent code itself (needs pandas; no GPU).

    python make_s1_text.py          # -> paper/S1_Text.tex

Every prompt is produced by the functions in code/memprop/agent.py, for task t000 of the task set
v2 and the records of Qwen2.5-7B's clean run in each memory condition, so the text is exactly what
the models received.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "code"))

from memprop import agent as A                                          # noqa: E402
from memprop.common import ROOT, fmt, load_config, read_jsonl_gz, run_name  # noqa: E402
from memprop.tasks import load_tasks                                    # noqa: E402

TASK, MODEL, STEP = "t000", "q07", 5


def block(title, text):
    return f"\\subsection*{{{title}}}\n\\begin{{Verbatim}}[fontsize=\\small]\n{text}\n\\end{{Verbatim}}\n"


def wrap(text, width=100):
    out = []
    for line in text.split("\n"):
        while len(line) > width:
            cut = line.rfind(" ", 0, width)
            cut = width if cut <= 0 else cut
            out.append(line[:cut])
            line = "    " + line[cut:].lstrip()
        out.append(line)
    return "\n".join(out)


def main():
    cfg = load_config()
    task = next(t for t in load_tasks(ROOT, "v2") if t["id"] == TASK)
    res = ROOT / cfg["tasksets"]["v2"]["results_dir"] / MODEL
    records = {}
    for c in cfg["memconds"]:
        rows = read_jsonl_gz(res / f"clean_{run_name('v2', cfg['agent_version'], MODEL, c)}.jsonl.gz")
        records[c] = next(r for r in rows if r["task"] == TASK)["records"]
    parts = [r"""% Generated by make_s1_text.py from code/memprop/agent.py -- do not edit by hand.
\documentclass[10pt]{article}
\usepackage[margin=1.8cm,a4paper]{geometry}
\usepackage{fancyvrb}
\pagestyle{empty}
\begin{document}
\noindent\textbf{S1 Text. Prompts and generation settings.}

\noindent All prompts below were rendered by the agent code (code/memprop/agent.py) for task """
             + TASK + r""" of the synthetic task set (v2), using the records of Qwen2.5-7B's clean run in each
memory condition. Long lines are wrapped here for printing only. Generation settings: greedy decoding
(temperature 0, seed """ + str(cfg["llm_seed"]) + r"""), at most """ + str(cfg["max_tokens_code"]) + r""" new tokens for a script, """
             + str(cfg["max_tokens_note"]) + " for a note and " + str(cfg["max_tokens_report"]) + r""" for the report; context window """
             + f"{cfg['max_model_len']:,}" + r""" tokens. In a history, printed output is shown up to """ + str(cfg["stdout_shown_chars"])
             + " characters and scripts up to " + f"{cfg['code_shown_chars']:,}" + r""" characters; longer text is cut in the
middle. A failed script gets one retry (""" + str(cfg["max_attempts"]) + r""" attempts in all).
"""]
    parts.append(block("System prompt for every script", wrap(A.SYSTEM_CODE)))
    for c in cfg["memconds"]:
        msgs = A.code_messages(task, c, records[c], STEP, cfg)
        parts.append(block(f"User prompt for step {STEP}, memory condition: {c}", wrap(msgs[1]["content"])))
    rec = records["notes"][STEP - 1]
    note = A.note_messages(task, STEP, rec["stdout"] or "", cfg)
    parts.append(block("Note prompt (notes condition only): system", wrap(A.SYSTEM_NOTE)))
    parts.append(block(f"Note prompt (notes condition only): user, step {STEP}", wrap(note[1]["content"])))
    retry = A.retry_messages([{"role": "user", "content": "..."}], "<the model's reply>",
                             "Traceback (most recent call last):\n  ...\nKeyError: 'weight'", "")
    parts.append(block("Retry message after a failed script (example error)", wrap(retry[-1]["content"])))
    rep = A.report_messages(task, "rawlog", records["rawlog"], cfg)
    parts.append(block("Report prompt: system", wrap(A.SYSTEM_REPORT)))
    parts.append(block("Report prompt: user (raw-log condition)", wrap(rep[1]["content"])))
    k, w = 2, 74.1832
    parts.append(block("Edited records of step k in the sham and inject arms (example value)",
                       "notes condition:            " + A.edited_note(k, fmt(w, False)) + "\n"
                       "raw log and full context:   " + A.edited_stdout(fmt(w, False)) + "\n"
                       "(in full context the script of step k stays as generated; only its output is edited)"))
    parts.append("\\end{document}\n")
    out = HERE / "paper" / "S1_Text.tex"
    out.write_text("\n".join(parts))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
